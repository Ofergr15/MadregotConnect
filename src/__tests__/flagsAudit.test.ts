import { describe, expect, it } from 'vitest';
import { execFileSync } from 'child_process';
import { readFileSync } from 'fs';
import { join } from 'path';
import { FEATURE_KEYS } from '@/lib/features/flags';

/**
 * Task 167: scripts/gen-flags-audit.mjs parses the FEATURES catalog with a regex, so
 * pin that it sees exactly the keys the type system sees. Deliberately NOT a
 * "the doc is current" check: every new read anywhere would fail other branches.
 */
const ROOT = join(__dirname, '..', '..');

describe('flags audit generator', () => {
  const out = JSON.parse(execFileSync('node', [join(ROOT, 'scripts', 'gen-flags-audit.mjs'), '--json'], { cwd: ROOT, encoding: 'utf8' })) as {
    keys: { key: string; status: string }[];
    constants: string[];
  };

  it('parses every FEATURES key, in order', () => {
    expect(out.keys.map((k) => k.key)).toEqual([...FEATURE_KEYS]);
  });

  it('classifies every key', () => {
    for (const k of out.keys) expect(['server-gated', 'web-read', 'native (branch)', 'catalog-only']).toContain(k.status);
  });

  it('finds the *_FOR_ALL constants', () => {
    expect(out.constants).toEqual(expect.arrayContaining(['SETUP_GATE_FOR_ALL', 'JOIN_UNIFIED_FOR_ALL', 'DAY_SESSION_FOR_ALL']));
  });

  it('a gated key is classified server-gated (race_live is enforced by its routes)', () => {
    expect(out.keys.find((k) => k.key === 'race_live')?.status).toBe('server-gated');
  });

  it('the doc keeps the generated markers', () => {
    const doc = readFileSync(join(ROOT, 'docs', 'flags-audit.md'), 'utf8');
    expect(doc).toContain('<!-- BEGIN:generated by scripts/gen-flags-audit.mjs -->');
    expect(doc).toContain('<!-- END:generated -->');
  });
});
