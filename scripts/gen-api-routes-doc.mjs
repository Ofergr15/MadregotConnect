#!/usr/bin/env node
// Regenerates docs/api-routes.md from src/app/api/**/route.ts.
//   node scripts/gen-api-routes-doc.mjs          → writes the file
//   node scripts/gen-api-routes-doc.mjs --check  → exits 1 if the file is stale
// Auth detail per route lives in docs/route-auth-inventory.md (queue task 1); this file
// is the map: what exists, which methods, what it is for, and the gate it calls.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { join, relative, sep } from 'path';

const ROOT = new URL('..', import.meta.url).pathname;
const API = join(ROOT, 'src', 'app', 'api');
const OUT = join(ROOT, 'docs', 'api-routes.md');

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) return walk(p);
    return n === 'route.ts' ? [p] : [];
  });
}

const GATE = /\b(resolveVerifiedCaller|mayActFor|requireMember|requireStaff\w*|requireCallerForAthlete|requirePackLeader|requireAcademyManager|requireStoryAdmin|requireContentStaff|requireApprover|requireDevice|requireAdmin\w*|verifyRequest|verifyImageUrl|verifyVideoUrl|isAuthorizedCron|CRON_SECRET)\b/g;

/** First sentence of the first JSDoc block or leading // comment run, trimmed to one line. */
function purpose(src) {
  const doc = /\/\*\*([\s\S]*?)\*\//.exec(src);
  let text = '';
  if (doc) {
    text = doc[1].split('\n').map((l) => l.replace(/^\s*\*\s?/, '').trim()).filter(Boolean)
      .join(' ');
  }
  text = text.replace(/`/g, '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
  const cut = text.search(/(?<=[.!?])\s/);
  text = cut > 0 ? text.slice(0, cut) : text;
  return text.length > 140 ? `${text.slice(0, 137)}…` : text;
}

export function build() {
  const rows = walk(API).sort().map((f) => {
    const src = readFileSync(f, 'utf8');
    const route = '/api/' + relative(API, f).split(sep).slice(0, -1).join('/');
    const methods = [...new Set([...src.matchAll(/export (?:async function|const) (GET|POST|PUT|PATCH|DELETE)\b/g)].map((m) => m[1]))].sort();
    const gates = [...new Set([...src.matchAll(GATE)].map((m) => (m[1] === 'CRON_SECRET' || m[1] === 'isAuthorizedCron' ? 'cron' : m[1])))].sort();
    const flags = [
      /export const dynamic\s*=\s*['"]force-dynamic['"]/.test(src) ? 'dyn' : '',
      /export const revalidate\s*=/.test(src) ? 'cached' : '',
      (/export const maxDuration\s*=\s*(\d+)/.exec(src) || [])[1] ? `${/export const maxDuration\s*=\s*(\d+)/.exec(src)[1]}s` : '',
    ].filter(Boolean).join(' ');
    const area = route.split('/')[2] || '';
    return { area, route, methods, gates, flags, purpose: purpose(src) };
  });
  const areas = [...new Set(rows.map((r) => r.area))];
  const lines = [
    '# API routes',
    '',
    `Generated by \`node scripts/gen-api-routes-doc.mjs\` from \`src/app/api/**/route.ts\` — ${rows.length} routes in ${areas.length} areas. Do not edit by hand; rerun the script.`,
    '',
    'Who may call each route, and why the public ones are safe, is in `docs/route-auth-inventory.md`. Conventions (response shape, `force-dynamic`, error handling) are in CLAUDE.md → "API conventions".',
    '',
    '`gate` = the auth helpers the route calls (`cron` = `Bearer CRON_SECRET`); empty means a local helper, a token in the URL, or a public route listed in the inventory. `flags`: `dyn` = `force-dynamic`, `cached` = `revalidate`, `Ns` = `maxDuration`.',
    '',
    '## Areas',
    '',
    areas.map((a) => `[\`${a}\`](#${a.replace(/[^\w-]/g, '').toLowerCase()}) (${rows.filter((r) => r.area === a).length})`).join(' · '),
    '',
  ];
  for (const a of areas) {
    lines.push(`## ${a}`, '', '| route | methods | gate | flags | purpose |', '|---|---|---|---|---|');
    for (const r of rows.filter((x) => x.area === a)) {
      lines.push(`| \`${r.route}\` | ${r.methods.join(',')} | ${r.gates.join(', ')} | ${r.flags} | ${r.purpose} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split(sep).pop())) {
  const md = build();
  if (process.argv.includes('--check')) {
    const cur = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
    if (cur !== md) { console.error('docs/api-routes.md is stale: run node scripts/gen-api-routes-doc.mjs'); process.exit(1); }
  } else {
    writeFileSync(OUT, md);
    console.log(`wrote ${relative(ROOT, OUT)}`);
  }
}
