#!/usr/bin/env node
// Regenerates the inventory tables in docs/flags-audit.md (task 167).
//   node scripts/gen-flags-audit.mjs          → rewrites the generated block
//   node scripts/gen-flags-audit.mjs --check  → exits 1 if the block is stale
//
// Read-only: greps this checkout (src/**, tests excluded) and, if the local branch
// `native-ios` exists, `git grep`s it for the same keys. Writes nothing but the doc.
// Everything outside the BEGIN/END markers in the doc is hand-written and kept.
import { execFileSync } from 'child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { join, relative, sep } from 'path';

const ROOT = new URL('..', import.meta.url).pathname;
const SRC = join(ROOT, 'src');
const OUT = join(ROOT, 'docs', 'flags-audit.md');
const FLAGS = join(SRC, 'lib', 'features', 'flags.ts');
const BEGIN = '<!-- BEGIN:generated by scripts/gen-flags-audit.mjs -->';
const END = '<!-- END:generated -->';

const rel = (p) => relative(ROOT, p).split(sep).join('/');

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) return n === '__tests__' || n === 'node_modules' ? [] : walk(p);
    return /\.(ts|tsx|mjs|js)$/.test(n) && !/\.test\.tsx?$/.test(n) ? [p] : [];
  });
}

// ── 1. The enablement catalog (feature_enablements, migration 191).
const flagsSrc = readFileSync(FLAGS, 'utf8');
const catalogBody = flagsSrc.slice(flagsSrc.indexOf('export const FEATURES = {'), flagsSrc.indexOf('} as const') > 0 ? flagsSrc.indexOf('} as const') : flagsSrc.indexOf('export type FeatureKey'));
const keys = [...catalogBody.matchAll(/^\s+([a-z][a-z0-9_]*): \{ label: '([^']*)', defaultEnabled: (true|false)/gm)].map((m) => ({
  key: m[1], label: m[2], defaultEnabled: m[3] === 'true',
}));
const publicKeys = new Set(
  [...(/PUBLIC_FEATURE_KEYS[^=]*=\s*\[([^\]]*)\]/.exec(flagsSrc)?.[1] ?? '').matchAll(/'([a-z0-9_]+)'/g)].map((m) => m[1]),
);
/** isAdminOnlyFeature in flags.ts: the management-screen keys. */
const adminOnly = { has: (k) => k.startsWith('native_mgmt_') };

const files = walk(SRC).filter((p) => p !== FLAGS);
const texts = new Map(files.map((p) => [p, readFileSync(p, 'utf8')]));

/** Server gate = a call that resolves the flag on the server. Client = a component/page reading /api/features/me. */
const GATE_RE = /isFeatureEnabled|featureResolutions?|enablementRows(For)?|requireFeature|gateFeature|featureOn|resolveFeature|resolveClubScope/;
function readsOf(key) {
  const lit = new RegExp(`(['"\`])${key}\\1`);
  // Only a line that names the key AND talks about features counts as a read: 'events',
  // 'calendar', 'search' are also table names, routes and i18n keys.
  const featureLine = (l) => lit.test(l) && (GATE_RE.test(l) || /feature|Feature|FEATURE|flag|Flag/.test(l));
  const server = [], client = [], other = [];
  for (const [p, t] of texts) {
    if (!lit.test(t)) continue;
    const r = rel(p);
    const isFeatureRead = t.split('\n').some(featureLine);
    if (!isFeatureRead) { other.push(r); continue; }
    if (r.startsWith('src/app/api/') || r.startsWith('src/lib/')) server.push(r);
    else client.push(r);
  }
  return { server, client, other };
}

// ── 2. The native app, read-only, from the `native-ios` branch if this clone has it.
let iosRef = null;
let iosHits = new Map();
try {
  const sha = execFileSync('git', ['rev-parse', '--verify', '--quiet', 'native-ios'], { cwd: ROOT, encoding: 'utf8' }).trim();
  const date = execFileSync('git', ['log', '-1', '--format=%cs', 'native-ios'], { cwd: ROOT, encoding: 'utf8' }).trim();
  iosRef = `native-ios @ ${sha.slice(0, 8)} (${date})`;
  for (const { key } of keys) {
    let out = '';
    try {
      out = execFileSync('git', ['grep', '-l', '-w', '-e', `"${key}"`, 'native-ios', '--', 'ios/'], { cwd: ROOT, encoding: 'utf8' });
    } catch { /* git grep exits 1 for no match */ }
    const hit = out.split('\n').filter(Boolean).map((l) => l.replace(/^native-ios:/, ''));
    if (hit.length) iosHits.set(key, hit);
  }
} catch { iosRef = null; }

// ── 3. Code-constant rollout switches (`export const X_FOR_ALL = true|false`).
const constFlags = [];
for (const [p, t] of texts) {
  for (const m of t.matchAll(/export const ([A-Z][A-Z0-9_]*_FOR_ALL) = (true|false)/g)) {
    const name = m[1];
    const readers = [...texts].filter(([q, u]) => q !== p && new RegExp(`\\b${name}\\b`).test(u)).map(([q]) => rel(q));
    constFlags.push({ name, value: m[2], file: rel(p), readers });
  }
}
constFlags.sort((a, b) => a.name.localeCompare(b.name));

// ── 4. app_settings kill switches the server reads by key.
const settingKeys = new Map();
for (const [p, t] of texts) {
  for (const m of t.matchAll(/(?:eq\('key',\s*|key:\s*)'([a-z0-9_]+_(?:mode|paused|enabled|open|disabled))'/g)) {
    if (!settingKeys.has(m[1])) settingKeys.set(m[1], new Set());
    settingKeys.get(m[1]).add(rel(p));
  }
}

// ── Render.
const short = (list, n = 3) => (list.length === 0 ? '—' : list.slice(0, n).map((f) => `\`${f.replace(/^src\//, '')}\``).join(', ') + (list.length > n ? ` +${list.length - n}` : ''));
const rows = keys.map(({ key, label, defaultEnabled }) => {
  const r = readsOf(key);
  const ios = iosHits.get(key) ?? [];
  let status;
  if (r.server.length) status = 'server-gated';
  else if (r.client.length) status = 'web-read';
  else if (ios.length) status = 'native (branch)';
  else status = 'catalog-only';
  return { key, label, defaultEnabled, ...r, ios, status };
});
const count = (s) => rows.filter((r) => r.status === s).length;

let md = `${BEGIN}\n\n`;
md += `Generated from \`src/lib/features/flags.ts\` and a grep of \`src/**\` (tests excluded)`;
md += iosRef ? `, plus a read-only \`git grep\` of \`${iosRef}\`.\n\n` : `. No local \`native-ios\` branch, so the iOS column is empty.\n\n`;
md += `**${rows.length} enablement keys**: ${count('server-gated')} server-gated, ${count('web-read')} read only by web UI, ${count('native (branch)')} read only on the native branch, **${count('catalog-only')} catalog-only** (no reader in this repo — served to the app by \`GET /api/features/me\` and nothing else).\n\n`;
md += `| key | label | default | public | server gate | web UI | other mentions | iOS (native-ios) | status |\n|---|---|---|---|---|---|---|---|---|\n`;
for (const r of rows) {
  md += `| \`${r.key}\` | ${r.label} | ${r.defaultEnabled ? 'on' : 'off'} | ${publicKeys.has(r.key) ? 'yes' : ''}${adminOnly.has(r.key) ? ' admin-only' : ''} | ${short(r.server)} | ${short(r.client)} | ${short(r.other, 2)} | ${short(r.ios, 2)} | ${r.status} |\n`;
}
md += `\n### Code-constant rollout switches (\`*_FOR_ALL\`)\n\n| constant | value | defined in | read by |\n|---|---|---|---|\n`;
for (const c of constFlags) md += `| \`${c.name}\` | \`${c.value}\` | \`${c.file.replace(/^src\//, '')}\` | ${short(c.readers, 4)} |\n`;
md += `\n### \`app_settings\` switches read by key\n\n| key | read/written in |\n|---|---|\n`;
for (const [k, set] of [...settingKeys].sort()) md += `| \`${k}\` | ${short([...set].sort(), 4)} |\n`;
md += `\n${END}`;

const doc = readFileSync(OUT, 'utf8');
const a = doc.indexOf(BEGIN), b = doc.indexOf(END);
if (a === -1 || b === -1) { console.error(`markers missing in ${rel(OUT)}`); process.exit(2); }
const next = doc.slice(0, a) + md + doc.slice(b + END.length);
if (process.argv.includes('--json')) {
  console.log(JSON.stringify({ keys: rows.map((r) => ({ key: r.key, status: r.status })), constants: constFlags.map((c) => c.name) }));
  process.exit(0);
}
if (process.argv.includes('--check')) {
  if (next !== doc) { console.error(`${rel(OUT)} is stale — run node scripts/gen-flags-audit.mjs`); process.exit(1); }
  console.log(`${rel(OUT)} is current`);
} else {
  writeFileSync(OUT, next);
  console.log(`wrote ${rel(OUT)}: ${rows.length} keys, ${constFlags.length} constants, ${settingKeys.size} settings`);
}
